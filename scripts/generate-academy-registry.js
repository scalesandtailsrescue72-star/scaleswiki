const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const root = process.cwd();
const dataDir = path.join(root, 'app', 'academy', 'data');
const academyDir = path.join(root, 'app', 'academy');
const courseOutFile = path.join(dataDir, '_generatedCourses.ts');
const lessonOutFile = path.join(dataDir, '_generatedLessonContent.ts');

const courseDirs = fs.readdirSync(dataDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .filter((name) => fs.existsSync(path.join(dataDir, name, 'course.ts')));

let imports = '';
const modulesArray = [];

courseDirs.forEach((name, idx) => {
  const varName = `m${idx}`;
  imports += `import * as ${varName} from './${name}/course';\n`;
  modulesArray.push(varName);
});

const courseContent = `// THIS FILE IS AUTO-GENERATED BY scripts/generate-academy-registry.js
// Do not edit by hand.
${imports}
export const modules = [${modulesArray.join(', ')}];
`;

fs.writeFileSync(courseOutFile, courseContent, 'utf8');

const lessonRegistry = {};

courseDirs.forEach((courseSlug) => {
  const contentDir = path.join(academyDir, courseSlug, 'content');

  if (!fs.existsSync(contentDir)) {
    return;
  }

  const files = fs.readdirSync(contentDir)
    .filter((name) => /^lesson-\d+\.md$/i.test(name))
    .sort();

  files.forEach((fileName) => {
    const match = fileName.match(/^lesson-(\d+)\.md$/i);
    if (!match) return;

    const lessonNumber = Number(match[1]);
    const raw = fs.readFileSync(path.join(contentDir, fileName), 'utf8');
    const parsed = matter(raw);

    lessonRegistry[`${courseSlug}:${lessonNumber}`] = {
      content: parsed.content,
      data: parsed.data,
    };
  });
});

const lessonContent = `// THIS FILE IS AUTO-GENERATED BY scripts/generate-academy-registry.js
// Do not edit by hand.

export type GeneratedLessonContent = {
  content: string;
  data: Record<string, unknown>;
};

export const generatedLessonContent: Record<string, GeneratedLessonContent> = ${JSON.stringify(lessonRegistry, null, 2)};
`;

fs.writeFileSync(lessonOutFile, lessonContent, 'utf8');
