const fs = require('fs');
const path = require('path');

const dataDir = path.join(process.cwd(), 'app', 'academy', 'data');
const outFile = path.join(dataDir, '_generatedCourses.ts');

const items = fs.readdirSync(dataDir, { withFileTypes: true })
  .filter(d => d.isDirectory())
  .map(d => d.name)
  .filter(name => fs.existsSync(path.join(dataDir, name, 'course.ts')));

let imports = '';
let modulesArray = [];

items.forEach((name, idx) => {
  const varName = `m${idx}`;
  imports += `import * as ${varName} from './${name}/course';\n`;
  modulesArray.push(varName);
});

const content = `// THIS FILE IS AUTO-GENERATED BY scripts/generate-academy-registry.js
// Do not edit by hand.
${imports}
export const modules = [${modulesArray.join(', ')}];
`;

fs.writeFileSync(outFile, content, 'utf8');
